# Branches in Git are parallel lines of development that allow users to work on features, fixes, or experiments independently of each other. In Git, the two main types of branches are the main branch (such as "main" or "master"), which typically represents the main line of development, and auxiliary branches, which are created to work on new features, bug fixes, or other tasks without affecting the main branch.

# List, create, delete, or rename branches within a repository.

git branch

# Create branches

git branch <branch_name>

# To switch between branches in Git

git checkout <branch_name>

# Create and switches to a new branch named <branch_name>

git checkout -b <branch_name>