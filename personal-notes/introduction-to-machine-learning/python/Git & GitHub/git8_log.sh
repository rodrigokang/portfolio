# Displays the commit history with the commit message, author, date, and a unique commit hash for each commit.

git log

# To provide a concise display of commit history in a single line, showing only the abbreviated commit hash and the commit message for each commit in a Git repository.

git log --oneline

# To provide a compact and visually informative representation of the Git commit history, including a concise one-line format, decoration with branch and tag names, a graph showing branching and merging, and displays information for all branches.

git log --oneline --decorate --all --graph